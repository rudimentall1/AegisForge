import os
import logging
import requests
import base64

logger = logging.getLogger("GitHubPR")

GITHUB_TOKEN = os.getenv("GITHUB_TOKEN", "")
DEFAULT_REPO = "rudimentall1/AegisForge"

def create_security_pull_request(repo_full_name: str, patch_path: str, vuln_type: str) -> str:
    """
    Creates a branch, commits the security patch, and opens a Pull Request on GitHub.
    """
    target_repo = repo_full_name if repo_full_name else DEFAULT_REPO
    patch_filename = os.path.basename(patch_path)
    try:
        with open(patch_path, "r", encoding="utf-8") as pf:
            patch_content = pf.read()
    except Exception as e:
        logger.error(f"[GitHub PR] Failed to read patch file: {e}")
        return ""

    headers = {
        "Authorization": f"Bearer {GITHUB_TOKEN}",
        "Accept": "application/vnd.github+json"
    }

    # 1. Получаем дефолтную ветку репозитория
    repo_url = f"https://api.github.com/repos/{target_repo}"
    resp = requests.get(repo_url, headers=headers)
    if resp.status_code != 200:
        logger.error(f"[GitHub PR] Failed to fetch repo info: {resp.text}")
        return ""

    default_branch = resp.json().get("default_branch", "main")

    # 2. Получаем SHA последней версии дефолтной ветки
    ref_url = f"https://api.github.com/repos/{target_repo}/git/ref/heads/{default_branch}"
    ref_resp = requests.get(ref_url, headers=headers)
    if ref_resp.status_code != 200:
        logger.error(f"[GitHub PR] Failed to get ref: {ref_resp.text}")
        return ""

    base_sha = ref_resp.json()["object"]["sha"]

    # 3. Создаем новую ветку для патча
    branch_name = f"aegisforge-fix-{os.path.splitext(patch_filename)[0]}"
    create_ref_url = f"https://api.github.com/repos/{target_repo}/git/refs"
    ref_payload = {
        "ref": f"refs/heads/{branch_name}",
        "sha": base_sha
    }
    requests.post(create_ref_url, json=ref_payload, headers=headers)

    # 4. Создаем или обновляем файл в новой ветке
    file_url = f"https://api.github.com/repos/{target_repo}/contents/patches/{patch_filename}"
    encoded_content = base64.b64encode(patch_content.encode("utf-8")).decode("utf-8")
    file_payload = {
        "message": f"security(aegisforge): auto-remediate {vuln_type}",
        "content": encoded_content,
        "branch": branch_name
    }
    requests.put(file_url, json=file_payload, headers=headers)

    # 5. Создаем Pull Request
    pr_url = f"https://api.github.com/repos/{target_repo}/pulls"
    pr_payload = {
        "title": f"🛡️ AegisForge Security Patch: {vuln_type}",
        "body": f"Automated security remediation generated by AegisForge autonomous agent.\n\n**Vulnerability:** {vuln_type}\nValidated via Foundry and Slither.",
        "head": branch_name,
        "base": default_branch
    }
    pr_resp = requests.post(pr_url, json=pr_payload, headers=headers)
    if pr_resp.status_code == 201:
        pr_link = pr_resp.json().get("html_url")
        logger.info(f"[GitHub PR] Pull Request created successfully: {pr_link}")
        return pr_link
    else:
        logger.error(f"[GitHub PR] Failed to create PR: {pr_resp.text}")
        return ""
